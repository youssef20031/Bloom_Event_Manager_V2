class BriefPdfRendererTest {

    @Test
    void rendersAllNineSectionsWithLabelsResolved() throws IOException {
        EventIntakeData data = new EventIntakeData("Acme Corp", "Jane", "jane@acme.test", "June 2026", "Tech",
                List.of("Bonding"), "Fun", "Curiosity", "Open", List.of("Collaborative"), "Silos", "Surveys", "no",
                "40", "full-day", "balanced", List.of("25-40"), "hybrid", "yes", "not-sure", "Cairo", "Near metro",
                List.of("Egyptian"), "Arabic, English", List.of("Halal"), "Cairo", "None", List.of(),
                List.of("Employees"), List.of("Cross-team"), "Energised", "Feel inspired and connected",
                List.of("Playful"), "Nothing scary",
                List.of("Lunch"), "1hour", "yes", List.of("Vegetarian"), "yes", "Tote bags", "Budget 50k");

        byte[] pdf = new BriefPdfRenderer().render(data);

        try (PDDocument doc = Loader.loadPDF(pdf)) {
            assertThat(doc.getNumberOfPages()).isGreaterThanOrEqualTo(1);
            String text = new PDFTextStripper().getText(doc);
            assertThat(text).contains("Acme Corp").contains("Event Intake & Customer Brief")
                    .contains("Client & Event Information").contains("Core Theme & Objectives")
                    .contains("Event Scope & Logistics").contains("Venue & Facilities")
                    .contains("Cultural Considerations").contains("Participant & Interaction Goals")
                    .contains("Activity Style & Tone").contains("Food & Amenities").contains("Additional Context")
                    .contains("Full-Day (approx. 6-8 hours, including breaks)")
                    .contains("A balanced mix of high-energy activities and focused downtime")
                    .contains("Hybrid (Indoor + Outdoor)")
                    .contains("Theatre / Stage: Yes").contains("Sound System: Not Sure / To Be Determined")
                    .contains("1 hour").contains("Yes (Tote bags)")
                    .contains("Generated by Bloom RAG System").contains("Page 1 of");
        }
    }

    /**
     * Regression guard: {@code finish()} used to draw the footer at
     * {@code PAGE_H - 40} and pass it straight to {@code drawText}, whose
     * last parameter is a raw PDF baseline (bottom-left origin) — unlike
     * every other call site in this renderer, which goes through
     * {@code text()}'s {@code PAGE_H - yFromTop - size} conversion. That put
     * the footer 40pt from the TOP of the page instead of the bottom,
     * overprinting the indigo header band on page 1. A plain
     * {@code PDFTextStripper} text search cannot catch this — it extracts
     * text regardless of where on the page it was drawn — so this walks each
     * footer glyph's real baseline the same way
     * {@code ChatPdfRendererTest.wrappedParagraphsNeverDrawOutsideThePageMargins}
     * does, via a stripper subclass that recovers the bottom-up baseline from
     * PDFBox's top-down TextPosition space.
     */
    @Test
    void footerSitsNearTheBottomOfEveryPageNotTheTop() throws IOException {
        EventIntakeData data = new EventIntakeData("Acme Corp", "Jane", "jane@acme.test", "June 2026", "Tech",
                List.of("Bonding"), "Fun", "Curiosity", "Open", List.of("Collaborative"), "Silos", "Surveys", "no",
                "40", "full-day", "balanced", List.of("25-40"), "hybrid", "yes", "not-sure", "Cairo", "Near metro",
                List.of("Egyptian"), "Arabic, English", List.of("Halal"), "Cairo", "None", List.of(),
                List.of("Employees"), List.of("Cross-team"), "Energised", "Feel inspired and connected",
                List.of("Playful"), "Nothing scary",
                List.of("Lunch"), "1hour", "yes", List.of("Vegetarian"), "yes", "Tote bags", "Budget 50k");

        byte[] pdf = new BriefPdfRenderer().render(data);

        float pageHeight = PDRectangle.A4.getHeight();
        List<Float> footerBaselines = new ArrayList<>();
        try (PDDocument doc = Loader.loadPDF(pdf)) {
            PDFTextStripper stripper = new PDFTextStripper() {
                @Override
                protected void writeString(String string, List<TextPosition> textPositions) throws IOException {
                    if (string.contains("Generated by Bloom RAG System") || string.startsWith("Page ")) {
                        for (TextPosition position : textPositions) {
                            footerBaselines.add(pageHeight - position.getY());
                        }
                    }
                }
            };
            stripper.getText(doc);
        }

        assertThat(footerBaselines).isNotEmpty();
        // footerY is 40pt from the bottom (BriefPdfRenderer.Writer#finish);
        // 100pt leaves headroom for the glyph's own height while staying far
        // below the 140pt indigo header band and the 80pt BOTTOM_MARGIN this
        // renderer's need() reserves above the footer.
        assertThat(footerBaselines).as("the footer must sit near the bottom of the page, not the top")
                .allSatisfy(baseline -> assertThat(baseline).isLessThan(100f));
    }

    @Test
    void emptyChecklistsSayNoneSelected() throws IOException {
        EventIntakeData data = new EventIntakeData("Acme", null, null, null, null, List.of(), null, null, null,
                List.of(), null, null, null, null, null, null, List.of(), null, null, null, null, null, List.of(), null,
                List.of(), null, null, List.of(), List.of(), List.of(), null, null, List.of(), null, List.of(), null, null,
                List.of(), null, null, null);

        try (PDDocument doc = Loader.loadPDF(new BriefPdfRenderer().render(data))) {
            assertThat(new PDFTextStripper().getText(doc)).contains("None selected").contains("—");
        }
    }

    @Test
    void nonWinAnsiTextInAFreeTextFieldDegradesToPlaceholdersRatherThanThrowing() throws IOException {
        // This renderer draws everything with Standard-14 Helvetica and has no
        // Arabic font by design (only the slide deck gets ICU4J shaping, per
        // the plan). Arabic reaching a free-text field is plausible input for
        // a Cairo-based business — V1 (PDFKit) never throws on an unsupported
        // glyph, it just can't draw it, so the parity target is "renders,
        // with placeholders" rather than "crashes the whole submission".
        EventIntakeData data = new EventIntakeData("Acme", null, null, null, null, List.of(), null, null, null,
                List.of(), null, null, null, null, null, null, List.of(), null, null, null, null, null, List.of(), null,
                List.of(), null, null, List.of(), List.of(), List.of(), null, null, List.of(), null, List.of(), null, null,
                List.of(), null, null, "مرحبا");

        byte[] pdf = new BriefPdfRenderer().render(data);

        try (PDDocument doc = Loader.loadPDF(pdf)) {
            assertThat(doc.getNumberOfPages()).isGreaterThanOrEqualTo(1);
            // Five Arabic letters, none encodable by Helvetica -> five placeholders.
            assertThat(new PDFTextStripper().getText(doc)).contains("?????");
        }
    }
}
